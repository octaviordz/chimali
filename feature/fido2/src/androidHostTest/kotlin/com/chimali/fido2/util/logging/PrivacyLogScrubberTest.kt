package com.chimali.fido2.util.logging

import kotlin.test.Test
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse

class PrivacyLogScrubberTest {
    /** @see NFR-SEC-041 and TR-AUTH-031 */
    @Test
    fun `scrub completely masks 24 word mnemonics`() {
        // Use a non-dictionary marker sequence rather than a valid, publicly known BIP-39 phrase.
        val sensitiveMnemonic = List(24) { "mockword" }.joinToString(" ")
        val message = "Failed to load master seed: $sensitiveMnemonic"

        val scrubbed = PrivacyLogScrubber.scrub(message)

        assertEquals("Failed to load master seed=[REDACTED]", scrubbed)
        assertFalse(scrubbed.contains("abandon"))
    }

    /** @see NFR-SEC-041 and TR-AUTH-031 */
    @Test
    fun `scrub completely masks 12 word mnemonics`() {
        val sensitiveMnemonic = List(12) { "mockword" }.joinToString(" ")
        val message = "Seed recovery failed: $sensitiveMnemonic"

        val scrubbed = PrivacyLogScrubber.scrub(message)

        assertEquals("Seed recovery failed: [REDACTED]", scrubbed)
    }

    /** @see NFR-SEC-041 and TR-AUTH-031 */
    @Test
    fun `scrub completely masks hex key material`() {
        // A recognizable synthetic marker, not key material generated by a crypto API.
        val privateKeyHex = "deadbeef".repeat(8)
        val message = "Generated KeyPair: private=$privateKeyHex"

        val scrubbed = PrivacyLogScrubber.scrub(message)

        assertEquals("Generated KeyPair: private=[REDACTED]", scrubbed)
        assertFalse(scrubbed.contains(privateKeyHex))
    }

    /** @see NFR-SEC-041 and TR-AUTH-031 */
    @Test
    fun `scrub redacts specific sensitive keywords`() {
        val message1 = "The password is mysecretpassword123!"
        val message2 = "User pin=123456 failed"

        val scrubbed1 = PrivacyLogScrubber.scrub(message1)
        val scrubbed2 = PrivacyLogScrubber.scrub(message2)

        assertEquals("The password=[REDACTED]", scrubbed1)
        assertEquals("User pin=[REDACTED]", scrubbed2)

        val formatMessage1 = "The password: mysecretpassword123!"
        val scrubbedFormat1 = PrivacyLogScrubber.scrub(formatMessage1)

        assertEquals("The password=[REDACTED]", scrubbedFormat1)
    }

    @Test
    fun `scrub consumes the complete message after a multiword sensitive value`() {
        val message = "password=two words, and more; elapsedMs=12\nstill-secret\npin=another-secret"

        val scrubbed = PrivacyLogScrubber.scrub(message)

        assertEquals("password=[REDACTED]", scrubbed)
        assertFalse(scrubbed.contains("and more"))
        assertFalse(scrubbed.contains("elapsedMs"))
        assertFalse(scrubbed.contains("still-secret"))
        assertFalse(scrubbed.contains("another-secret"))
    }

    /** @see NFR-SEC-041 and TR-AUTH-031 */
    @Test
    fun `scrub redacts derivation secrets and private material labels with spaces`() {
        val fields =
            listOf(
                "prk=synthetic-prk" to "prk=[REDACTED]",
                "private key: synthetic-private-key" to "private key=[REDACTED]",
                "root key=synthetic-root" to "root key=[REDACTED]",
                "factor=synthetic-factor" to "factor=[REDACTED]",
            )

        fields.forEach { (field, expected) ->
            val scrubbed = PrivacyLogScrubber.scrub(field)
            assertEquals(expected, scrubbed)
            assertFalse(scrubbed.contains("synthetic-"))
        }
    }

    /** @see NFR-SEC-041 and TR-AUTH-031 */
    @Test
    fun `scrub redacts every sensitive keyword in one pass`() {
        val keywords =
            listOf(
                "password",
                "pin",
                "prk",
                "privateKey",
                "private key",
                "private_key",
                "privateScalar",
                "private scalar",
                "private_scalar",
                "seed",
                "mnemonic",
                "secret",
                "secretKey",
                "rootKey",
                "root key",
                "root_key",
                "factor",
            )
        keywords.forEach { keyword ->
            val scrubbed = PrivacyLogScrubber.scrub("$keyword=synthetic-value")
            assertEquals("$keyword=[REDACTED]", scrubbed)
            assertFalse(scrubbed.contains("synthetic-value"))
        }
        assertEquals("SECRET=[REDACTED]", PrivacyLogScrubber.scrub("SECRET=synthetic-value"))
    }

    /** @see NFR-SEC-041 and TR-AUTH-031 */
    @Test
    fun `scrub ignores normal text`() {
        val message = "Connection lost during Bluetooth transmission"
        val scrubbed = PrivacyLogScrubber.scrub(message)

        assertEquals("Connection lost during Bluetooth transmission", scrubbed)
    }
}
